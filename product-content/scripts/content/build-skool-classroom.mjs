/**
 * Turns a Skool classroom export into courses the site can show.
 *
 *   node scripts/content/build-skool-classroom.mjs ai-video-club
 *
 * reads content/courses/<name>/classroom.json — one entry per Skool course,
 * each with its lessons in sidebar order and the set (module) heading each
 * sat under — and writes lib/courses/<name>.generated.ts exporting Course[].
 * The export itself is made by driving the signed-in browser through the
 * classroom (the lesson text only renders on screen); this file is only the
 * shape change.
 */
import fs from "node:fs";
import path from "node:path";

const name = process.argv[2];
if (!name) { console.error("which classroom? e.g. ai-video-club"); process.exit(1); }
const src = path.join("content", "courses", name, "classroom.json");
const out = path.join("lib", "courses", `${name}.generated.ts`);
const data = JSON.parse(fs.readFileSync(src, "utf8"));

const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "").slice(0, 60);
/* "1 · Start Here" → "Start Here"; "2b · Character Lock (Bonus)" keeps its tail. */
const clean = (t) => t.replace(/^[0-9]+[a-z]?\s*·\s*/, "").trim();

const courses = data.map((c, ci) => {
  /* Lessons under the same set heading make a module; lessons with none
     make one module named for the course. */
  const modules = [];
  for (const l of c.lessons) {
    const title = l.module || clean(c.title);
    let m = modules[modules.length - 1];
    if (!m || m.title !== title) { m = { title, lessons: [] }; modules.push(m); }
    m.lessons.push(l);
  }
  let n = 0;
  return {
    slug: slugify(clean(c.title)) || `course-${ci + 1}`,
    title: clean(c.title),
    blurb: c.blurb,
    cover: null,
    modules: modules.map((m, mi) => ({
      num: mi + 1,
      title: m.title,
      lessons: m.lessons.map((l, li) => {
        n++;
        return {
          num: `${mi + 1}.${li + 1}`,
          title: l.title,
          slug: slugify(l.title) || `lesson-${n}`,
          icon: null,
          banner: null,
          body: String(l.body || "").split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean),
          task: null,
          skool: `${c.url}?md=${l.md}`,
          ...(l.video && l.video !== "video" ? { video: l.video } : {}),
        };
      }),
    })),
  };
});

/* Two lessons with the same slug in one course would be one address. */
for (const c of courses) {
  const seen = new Set();
  for (const m of c.modules) for (const l of m.lessons) {
    let s = l.slug, k = 2;
    while (seen.has(s)) s = `${l.slug}-${k++}`;
    seen.add(s); l.slug = s;
  }
}

const banner = `/* Generated by scripts/content/build-skool-classroom.mjs from ${src}.\n   Do not edit by hand: re-export the classroom and run the script. */\n`;
fs.writeFileSync(out, `${banner}import type { Course } from "@/lib/courses/codex-mastery";\n\nexport const COURSES: Course[] = ${JSON.stringify(courses, null, 2)};\n`);
console.log(`${out}: ${courses.length} courses, ${courses.reduce((a, c) => a + c.modules.reduce((b, m) => b + m.lessons.length, 0), 0)} lessons`);
